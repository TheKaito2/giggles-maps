-- Giggles Maps core schema: places, shops, routes, check-ins, billing, badges.
create extension if not exists postgis with schema extensions;

-- ---------- tables ----------
create table public.profiles (
  id uuid primary key references auth.users on delete cascade,
  display_name text,
  created_at timestamptz not null default now()
);

create table public.shops (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references auth.users on delete set null,
  name text not null,
  wallet_thb numeric(12,2) not null default 0 check (wallet_thb >= 0),
  is_demo boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.places (
  id bigint generated by default as identity primary key,
  name text not null,
  name_th text,
  category text not null,               -- cafe, food, craft, temple, viewpoint, museum, park, market
  description text,
  location extensions.geography(point, 4326) not null,
  open_min int check (open_min between 0 and 1440),   -- minutes after midnight, null = always open
  close_min int check (close_min between 0 and 1440),
  dwell_min int not null default 15 check (dwell_min > 0),
  rating numeric(2,1) not null default 4.2 check (rating between 0 and 5),
  is_partner boolean not null default false,
  bid_thb numeric(8,2) not null default 0 check (bid_thb >= 0),
  shop_id uuid references public.shops on delete set null,
  is_demo boolean not null default false,
  source text not null default 'osm',   -- osm | province | team
  osm_id text unique,
  created_at timestamptz not null default now()
);
create index places_location_idx on public.places using gist (location);

create table public.routes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users on delete cascade,
  origin extensions.geography(point, 4326) not null,
  dest extensions.geography(point, 4326) not null,
  start_min int not null,
  budget_min int not null,
  extra_min numeric(6,1) not null,
  created_at timestamptz not null default now()
);

-- every stop we show is an impression; verified visits / impressions = p_checkin
create table public.route_stops (
  route_id uuid references public.routes on delete cascade,
  place_id bigint references public.places on delete cascade,
  position int not null,
  bid_thb numeric(8,2) not null default 0,
  primary key (route_id, place_id)
);

create table public.checkins (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users on delete cascade,
  place_id bigint not null references public.places on delete cascade,
  location extensions.geography(point, 4326) not null,
  accuracy_m real not null,
  distance_m real not null,
  selfie_path text,
  face_count int not null default 0,
  client jsonb not null default '{}',
  status text not null check (status in ('approved', 'review', 'rejected')),
  reasons text[] not null default '{}',
  rewarded boolean not null default false,
  created_at timestamptz not null default now()
);
create index checkins_user_time_idx on public.checkins (user_id, created_at desc);

create table public.billable_visits (
  id bigint generated by default as identity primary key,
  checkin_id uuid unique not null references public.checkins on delete cascade,
  place_id bigint not null references public.places,
  shop_id uuid not null references public.shops,
  amount_thb numeric(8,2) not null,
  created_at timestamptz not null default now()
);

create table public.collections (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  description text,
  required_count int not null default 3 check (required_count > 0)
);

create table public.collection_places (
  collection_id bigint references public.collections on delete cascade,
  place_id bigint references public.places on delete cascade,
  primary key (collection_id, place_id)
);

create table public.user_badges (
  user_id uuid references auth.users on delete cascade,
  collection_id bigint references public.collections on delete cascade,
  earned_at timestamptz not null default now(),
  primary key (user_id, collection_id)
);

create table public.wallet_topups (
  id bigint generated by default as identity primary key,
  shop_id uuid not null references public.shops,
  stripe_session_id text unique not null,
  amount_thb numeric(12,2) not null,
  created_at timestamptz not null default now()
);

